    private void SignupBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SignupBtnActionPerformed
        // TODO add your handling code here:
        String pw = String.valueOf(txtPass.getPassword());
        String cmbx = String.valueOf(txtQues.getSelectedItem());
    
        if (txtUname.getText().isEmpty() || txtFname.getText().isEmpty() || txtLname.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Don't leave the fields empty");
        } else if (pw.equals("")) {
            JOptionPane.showMessageDialog(null, "Don't leave the password empty");
        } else if (txtAns.getText().isEmpty() || txtQues.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(null, "Don't leave the security answer or question empty");
        } else {
            String sql = "INSERT INTO `user`(`uname`, `pass`, `fname`, `lname`, `ques`, `ans`, `designation`) VALUES (?,?,?,?,?,?,?)";
            try {
                ps = conn.prepareStatement(sql);
    
                ps.setString(1, txtUname.getText());
                ps.setString(2, String.valueOf(txtPass.getPassword()));
                ps.setString(3, txtFname.getText());
                ps.setString(4, txtLname.getText());
                ps.setString(5, String.valueOf(txtQues.getSelectedItem()));
                ps.setString(6, txtAns.getText());
                ps.setString(7, (String) txtCombo.getSelectedItem()); // Assuming txtCombo is your designation combo box
    
                ps.execute();
                JOptionPane.showMessageDialog(null, "Data Saved Successfully!");
                loginForm l = new loginForm();
                l.setVisible(true);
                this.dispose();
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(null, "Error saving data: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_SignupBtnActionPerformed

